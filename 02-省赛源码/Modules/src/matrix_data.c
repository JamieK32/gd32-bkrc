void reverse_blocks_u8(uint8_t *data, size_t len, size_t block_size)
{
    if (!data || block_size == 0) return;
    if (len < block_size) return;
    if (len % block_size != 0) return;  // 必须整块，否则你要定义尾巴怎么处理

    size_t blocks = len / block_size;

    for (size_t b = 0; b < blocks / 2; b++) {
        size_t left  = b * block_size;
        size_t right = (blocks - 1 - b) * block_size;

        // 交换两个块
        for (size_t i = 0; i < block_size; i++) {
            uint8_t tmp = data[left + i];
            data[left + i] = data[right + i];
            data[right + i] = tmp;
        }
    }
}

